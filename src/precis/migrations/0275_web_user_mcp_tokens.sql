-- Personal MCP credentials are independent of install/slice credentials.
-- No raw token persists; web_users IDs survive login/display-name changes.
CREATE TABLE IF NOT EXISTS web_user_mcp_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES web_users(id) ON DELETE CASCADE,
    label text NOT NULL CHECK (length(btrim(label)) BETWEEN 1 AND 100),
    token_sha256 text NOT NULL UNIQUE CHECK (token_sha256 ~ '^[0-9a-f]{64}$'),
    created_at timestamptz NOT NULL DEFAULT now(),
    revoked_at timestamptz
);

CREATE INDEX IF NOT EXISTS web_user_mcp_tokens_user_id_idx
    ON web_user_mcp_tokens (user_id);

COMMENT ON TABLE web_user_mcp_tokens IS
    'Revocable personal MCP credentials; SHA-256 only, raw token shown once.';
