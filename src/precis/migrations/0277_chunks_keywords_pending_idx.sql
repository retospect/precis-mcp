-- 0277_chunks_keywords_pending_idx.sql
--
-- Guard for the chunk_keywords fresh-backlog partial index (gr520236,
-- gr550973; spec docs/backlog/chunk-keywords-pending-index.md). The
-- tier-2 claim is `WHERE keywords IS NULL ... ORDER BY chunk_id DESC`
-- and only uses the index when its WHERE implies the index predicate,
-- so the predicate literals are owned in Python
-- (workers/chunk_keywords.py::_eligibility_sql / PENDING_INDEX_DDL) and
-- mirrored here; a test pins them together.
--
-- Prod's chunks (~4.7M rows) must NOT get an inline CREATE INDEX: it
-- takes a SHARE lock for a full heap scan and stalls ingest. Ops built
-- it CONCURRENTLY out of band. This migration therefore only guards:
--
--   * index present and valid, predicate as expected -> NO DDL at all
--     (not even CREATE INDEX IF NOT EXISTS, which takes the table lock
--     before it notices the name exists);
--   * index INVALID (failed CONCURRENTLY build) -> refuse;
--   * index present with a different predicate (the claim could never
--     use it) -> refuse;
--   * index missing and chunks reltuples > 1M -> refuse, never build;
--   * index missing on a small dev/test/fresh DB -> build in-transaction
--     (cheap at that size).
--
-- Rebuild recipe when refused (outside a transaction):
--   DROP INDEX CONCURRENTLY IF EXISTS chunks_keywords_pending_idx;
--   then the CREATE INDEX CONCURRENTLY statement in `rebuild` below.
--
-- Forward-only (ADR 0005). Idempotent. The baseline snapshot is
-- regenerated by scripts/bump, not edited here.

BEGIN;

SET LOCAL lock_timeout = '5s';

DO $$
DECLARE
    pred text;
    -- The predicate as pg_get_expr PRINTS it: NOT IN deparses to
    -- <> ALL over an ARRAY literal, every literal with an explicit
    -- ::text cast.
    want_pred constant text := '((keywords IS NULL) AND (chunk_kind <> ALL (ARRAY[''card_authors''::text, ''card_combined''::text, ''card_description''::text, ''card_title''::text, ''equation''::text, ''figure''::text, ''paper_note''::text, ''references''::text, ''scan_geometry''::text, ''table''::text])) AND (length(text) >= 150) AND ((meta ->> ''no_index''::text) IS DISTINCT FROM ''true''::text))';
    ddl constant text := 'CREATE INDEX %s chunks_keywords_pending_idx ON chunks (chunk_id DESC) WHERE keywords IS NULL AND chunk_kind NOT IN (''card_authors'', ''card_combined'', ''card_description'', ''card_title'', ''equation'', ''figure'', ''paper_note'', ''references'', ''scan_geometry'', ''table'') AND length(text) >= 150 AND (meta->>''no_index'') IS DISTINCT FROM ''true''';
    rebuild constant text := 'DROP INDEX CONCURRENTLY IF EXISTS chunks_keywords_pending_idx; ' || format(ddl, 'CONCURRENTLY') || ' -- outside a transaction, then re-apply';
    is_valid boolean;
BEGIN
    SELECT i.indisvalid, pg_get_expr(i.indpred, i.indrelid)
      INTO is_valid, pred
      FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid
     WHERE c.relname = 'chunks_keywords_pending_idx'
       AND c.relnamespace = 'public'::regnamespace;

    IF FOUND THEN
        IF NOT is_valid THEN
            RAISE EXCEPTION '0277: chunks_keywords_pending_idx exists but is INVALID (a failed CONCURRENTLY build)'
                USING HINT = rebuild;
        END IF;
        IF pred IS DISTINCT FROM want_pred THEN
            RAISE EXCEPTION '0277: chunks_keywords_pending_idx has an unexpected predicate, the claim cannot use it: %',
                    COALESCE(pred, '(none: the index is not partial)')
                USING HINT = rebuild;
        END IF;
        RETURN;  -- valid and exact: no DDL, no table lock
    END IF;

    IF (SELECT reltuples FROM pg_class
         WHERE relname = 'chunks' AND relnamespace = 'public'::regnamespace) > 1000000 THEN
        RAISE EXCEPTION '0277: chunks_keywords_pending_idx missing on a large chunks table; refusing to build inline'
            USING HINT = rebuild;
    END IF;

    EXECUTE format(ddl, '');
END
$$;

COMMIT;

