-- 0332_client_capability_tokens.sql
--
-- gr595554: the third bearer class — a client capability token. It names
-- a consumer (a claude.ai chat connector, a podcast listener), not a
-- person, so it sits beside web_user_mcp_tokens rather than in it: the
-- owning web_users row is only the minter/revoker, never an identity the
-- token authenticates. `scopes` is the per-token allow-list of
-- kinds/verbs (`read`, `read:<kind>`, `write:<kind>`, `feed`; default
-- `{read}` — the full read surface). Digest-only storage; the plaintext
-- is shown once at mint and never vaulted.
--
-- The podcast feed credential folds into this class: the per-listener
-- ``?t=`` bearer becomes a feed-scoped capability token. Its digest is
-- already a bare SHA-256, so existing subscribe URLs keep working — the
-- digest moves verbatim, the column it lived in goes away. The vault's
-- plaintext copy (``precis.users.feed_token_secret_name``) is untouched:
-- it is display-only, never the verification path.

CREATE TABLE IF NOT EXISTS web_user_capability_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES web_users(id) ON DELETE CASCADE,
    label text NOT NULL CHECK (length(btrim(label)) BETWEEN 1 AND 100),
    token_sha256 text NOT NULL UNIQUE CHECK (token_sha256 ~ '^[0-9a-f]{64}$'),
    scopes text[] NOT NULL CHECK (cardinality(scopes) > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    revoked_at timestamptz
);

CREATE INDEX IF NOT EXISTS web_user_capability_tokens_user_id_idx
    ON web_user_capability_tokens (user_id);

COMMENT ON TABLE web_user_capability_tokens IS
    'Revocable client capability credentials (gr595554); SHA-256 only, '
    'scope is a per-token allow-list of kinds/verbs, raw shown once.';

INSERT INTO web_user_capability_tokens (user_id, label, token_sha256, scopes)
SELECT id, 'podcast feed', feed_token_sha256, '{feed}'::text[]
FROM web_users
WHERE feed_token_sha256 IS NOT NULL;

-- Every reader/writer of the column ships in this same commit (the
-- _users_ops feed helpers and _USER_COLS), and the deploy's single-writer
-- window means no old binary ever queries it.
-- squawk-ignore ban-drop-column
ALTER TABLE web_users DROP COLUMN IF EXISTS feed_token_sha256;
