-- 0318_mcp_capability_tokens.sql
--
-- gr595554: the third bearer class — a client capability token. It
-- names a consumer (a claude.ai chat connector, a podcast listener),
-- not a person, so it sits beside web_user_mcp_tokens rather than in
-- it: the owning web_users row is only the minter/revoker, never an
-- identity the token authenticates. `scopes` is the per-token
-- allow-list of kinds/verbs (`read`, `read:<kind>`, `write:<kind>`,
-- `feed`; default `{read}` — the full read surface). Digest-only
-- storage; the plaintext is shown once at mint and never vaulted.

CREATE TABLE IF NOT EXISTS web_user_capability_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES web_users(id) ON DELETE CASCADE,
    label text NOT NULL CHECK (length(btrim(label)) BETWEEN 1 AND 100),
    token_sha256 text NOT NULL UNIQUE CHECK (token_sha256 ~ '^[0-9a-f]{64}$'),
    scopes text[] NOT NULL CHECK (cardinality(scopes) > 0),
    created_at timestamptz NOT NULL DEFAULT now(),
    revoked_at timestamptz
);

CREATE INDEX IF NOT EXISTS web_user_capability_tokens_user_id_idx
    ON web_user_capability_tokens (user_id);

COMMENT ON TABLE web_user_capability_tokens IS
    'Revocable client capability credentials (gr595554); SHA-256 only, '
    'scope is a per-token allow-list of kinds/verbs, raw shown once.';
