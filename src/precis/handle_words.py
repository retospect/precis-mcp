_BASE = 128
assert len(_COLORS) == len(_ADJECTIVES) == len(_NOUNS) == _BASE
assert len(set(_COLORS + _ADJECTIVES + _NOUNS)) == 3 * _BASE

_MIN_WORDS = 3
_LISTS = (_NOUNS, _ADJECTIVES, _COLORS)  # least-significant digit first
_WORD_RE = re.compile(r"[a-z]+")


def _list_at(pos: int) -> list[str]:
    """List for digit ``pos`` (0 = least significant); extras alternate."""
    if pos < len(_LISTS):
        return _LISTS[pos]
    return _ADJECTIVES if pos % 2 else _COLORS


def to_words(n: int) -> str:
    """Spoken form of non-negative ``n``: ``"<colour> <adjective> <noun>"``."""
    if n < 0:
        raise ValueError("id must be >= 0")
    digits: list[int] = []
    while n or len(digits) < _MIN_WORDS:
        n, d = divmod(n, _BASE)
        digits.append(d)
    return " ".join(_list_at(i)[d] for i, d in reversed(list(enumerate(digits))))


def to_number(words: str) -> int:
    """Inverse of :func:`to_words`; accepts spaces, hyphens, commas, any case.

    Raises ``ValueError`` naming the first problem (wrong word count, a word
    not on the expected list, or a non-canonical leading zero word).
    """
    toks = _WORD_RE.findall(words.lower())
    if len(toks) < _MIN_WORDS:
        raise ValueError(f"need at least {_MIN_WORDS} words, got {len(toks)}")
    n = 0
    top = len(toks) - 1
    for i, tok in enumerate(toks):
        pos = top - i
        lst = _list_at(pos)
        if tok not in lst:
            raise ValueError(f"{tok!r} is not a valid word at position {i + 1}")
        d = lst.index(tok)
        if i == 0 and d == 0 and len(toks) > _MIN_WORDS:
            raise ValueError("non-canonical handle (leading zero word)")
        n = n * _BASE + d
    return n
