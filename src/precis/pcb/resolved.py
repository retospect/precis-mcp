"""The resolved netlist snapshot (Slice 7 of pcb-lazy-netlist-and-checks).

The authored netlist (``pcb_netconns``) is intent; the solve's assignment
is derived. A snapshot is the FULL effective ``(pin, net)`` set one resolve
produced, plus the prior it was solved from and the intent's
``content_hash`` (``pcb_netlist_snapshots``). Readers build their IR from
:func:`apply` (the authored graph with the latest snapshot laid over it),
never from a patch replayed onto an IR.

Each snapshot pin records its ``declared`` net (the authored net when the
snapshot was solved). :func:`apply` honours an entry only while the pin's
authored net still equals it, so an edit to the intent wins over a stale
assignment until the next resolve. A pin with no declared net that the
solve bound (a spare supply channel taking a client's net, Reto 2026-10-16
ruling 2a) is ``solver_created``: it exists only here, is never written
back to ``pcb_netconns``, and is regenerated by the next solve.

Pure: no DB, no IR mutation. Design: docs/backlog/pcb-lazy-netlist-and-checks.md.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from typing import Any

from precis.pcb import matching as pcb_matching

Pin = tuple[str, str]


def declared_pin_nets(graph: Mapping[str, Any]) -> dict[Pin, str | None]:
    """Every pin the graph names, with its authored net (``None`` for a
    pin in ``graph["unconnected"]``)."""
    out: dict[Pin, str | None] = {}
    for net in graph.get("nets") or []:
        for m in net.get("members") or []:
            out.setdefault((str(m["refdes"]), str(m.get("pin") or "1")), net["name"])
    for m in graph.get("unconnected") or []:
        out.setdefault((str(m["refdes"]), str(m["pin"])), None)
    return out


def _pin_order(graph: Mapping[str, Any]) -> list[list[str]]:
    """The order :func:`precis.pcb.ir.from_graph` creates pins in for the
    authored graph: sorted net members, then the unconnected pins. A
    rebound graph keeps it so synthesized land patterns (assigned in pin
    creation order) do not move when a net moves between pins."""
    seen: set[Pin] = set()
    order: list[list[str]] = []
    for net in graph.get("nets") or []:
        members = sorted(
            net.get("members") or [],
            key=lambda m: (str(m["refdes"]), str(m.get("pin") or "1")),
        )
        for m in members:
            key = (str(m["refdes"]), str(m.get("pin") or "1"))
            if key not in seen:
                seen.add(key)
                order.append([key[0], key[1]])
    for m in graph.get("unconnected") or []:
        key = (str(m["refdes"]), str(m["pin"]))
        if key not in seen:
            seen.add(key)
            order.append([key[0], key[1]])
    return order


def rebind(
    graph: Mapping[str, Any], pin_nets: Mapping[Pin, str | None]
) -> dict[str, Any]:
    """``graph`` with each pin in ``pin_nets`` moved onto the named net
    (``None`` = unconnected). Net rows keep their attributes and order; a
    name that is not one of the graph's nets is ignored for that pin.
    Pins not in ``pin_nets`` keep their authored net. The result carries
    ``pin_order`` (see :func:`_pin_order`)."""
    nets = list(graph.get("nets") or [])
    names = {str(n["name"]) for n in nets}
    rows: dict[Pin, dict[str, Any]] = {}
    current: dict[Pin, str | None] = {}
    for net in nets:
        for m in net.get("members") or []:
            key = (str(m["refdes"]), str(m.get("pin") or "1"))
            rows.setdefault(key, m)
            current.setdefault(key, str(net["name"]))
    for m in graph.get("unconnected") or []:
        key = (str(m["refdes"]), str(m["pin"]))
        rows.setdefault(key, m)
        current.setdefault(key, None)
    target = dict(current)
    for key, net_name in pin_nets.items():
        if key in rows and (net_name is None or net_name in names):
            target[key] = net_name
    members: dict[str, list[dict[str, Any]]] = {str(n["name"]): [] for n in nets}
    unconnected: list[dict[str, Any]] = []
    for key, row in rows.items():
        net_name = target[key]
        if net_name is None:
            if current[key] is not None:
                # A supply pin the solve released is a spare, not a pin the
                # author forgot to wire: the §1j `unused` marker says so,
                # so `unconnected_pin` stays quiet (`must_terminate` still
                # overrides it).
                row = {**row, "meta": {**(row.get("meta") or {}), "unused": True}}
            unconnected.append({**row, "refdes": key[0], "pin": key[1]})
        else:
            members[net_name].append({**row, "refdes": key[0], "pin": key[1]})
    return {
        **graph,
        "nets": [{**n, "members": members[str(n["name"])]} for n in nets],
        "unconnected": unconnected,
        "pin_order": graph.get("pin_order") or _pin_order(graph),
    }


def apply(
    graph: Mapping[str, Any], snapshot: Mapping[str, Any] | None
) -> dict[str, Any]:
    """The effective graph: the authored ``graph`` with ``snapshot``'s
    assignment laid over it. An entry is stale when its pin's authored net
    no longer equals the entry's ``declared`` net (the intent was edited
    since the solve); every entry whose net or declared net a stale entry
    touches is dropped with it, so a swap pair never half-applies and a
    spare never keeps a net its client has left. Dropped pins and pins the
    snapshot does not list keep their authored net until the next resolve.
    ``None`` (no resolve yet) returns the graph unchanged."""
    if not snapshot or not snapshot.get("pins"):
        return dict(graph)
    declared = declared_pin_nets(graph)
    live: dict[Pin, dict[str, Any]] = {}
    dirty: set[str] = set()
    for e in snapshot["pins"]:
        key = (str(e["refdes"]), str(e["pin"]))
        if key not in declared:
            continue
        if declared[key] == e.get("declared"):
            live[key] = e
        else:
            dirty.update(n for n in (e.get("net"), e.get("declared")) if n)
            dirty.update(n for n in (declared[key],) if n)
    changed = True
    while changed:
        changed = False
        for key, e in list(live.items()):
            touched = {n for n in (e.get("net"), e.get("declared")) if n}
            if touched & dirty:
                del live[key]
                dirty |= touched
                changed = True
    return rebind(graph, {key: e.get("net") for key, e in live.items()})


def snapshot_pins(ir: Any, declared: Mapping[Pin, str | None]) -> list[dict[str, Any]]:
    """The FULL effective ``(pin, net)`` set off a settled IR, sorted by
    ``(refdes, pin)``: every pin (netless ones with ``net: None``), its
    ``declared`` net, and ``solver_created: True`` where a pin with no
    declared net now carries one."""
    from precis.pcb import ir as pcb_ir

    out: list[dict[str, Any]] = []
    for p in range(ir.n_pins):
        key = (str(ir.instance_refdes[int(ir.pin_instance[p])]), str(ir.pin_label[p]))
        n = int(ir.pin_net[p])
        net = None if n == pcb_ir.NO_NET else str(ir.net_name[n])
        entry: dict[str, Any] = {
            "refdes": key[0],
            "pin": key[1],
            "net": net,
            "declared": declared.get(key),
        }
        if net is not None and declared.get(key) is None:
            entry["solver_created"] = True
        out.append(entry)
    out.sort(key=lambda e: (e["refdes"], e["pin"]))
    return out


def prior_assignment(
    clients: Sequence[pcb_matching.Client],
    supplies: Sequence[pcb_matching.Supply],
    pin_nets: Mapping[Pin, str | None],
) -> dict[Pin, Pin]:
    """Client pin -> supply terminal under ``pin_nets`` (the effective
    nets the solve starts from) — the prior the next solve is warm-started
    and tie-broken with, and the one stored beside the snapshot."""
    return {
        row.client: row.supplier
        for row in pcb_matching.channel_map(clients, supplies, pin_nets)
        if row.supplier is not None
    }


def encode_prior(prior: Mapping[Pin, Pin]) -> list[list[str]]:
    """``prior`` as a sorted JSON list of ``[c_refdes, c_pin, s_refdes,
    s_pin]`` rows, the stored form."""
    return sorted([c[0], c[1], s[0], s[1]] for c, s in prior.items())


