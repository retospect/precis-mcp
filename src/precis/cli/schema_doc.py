"""``precis schema-doc`` — generate a Mermaid ER diagram of the DB.

Introspects ``information_schema`` for base-table columns + foreign
keys (plus ``pg_catalog.col_description`` comments) and renders a
Markdown file (default ``docs/reference/schema.md``) carrying a Mermaid
``erDiagram``, a compact table listing, and a searchable per-table
column list (name, type, key, ``COMMENT ON COLUMN`` text — gr513884:
the diagram alone is not greppable for a column's meaning). A
*generated* artifact — checked in
so GitHub renders it inline, and regenerated rather than hand-edited
so it cannot drift from the live schema (which the hand-drawn
``schema-v2.puml`` did).

Two row transports, one renderer:

* ``--dsn`` (default ``PRECIS_DATABASE_URL``) — connect with psycopg
  and run the query. Works inside the container / on a cluster node.
* ``--from-tsv PATH|-`` — read pre-fetched tab-separated rows. The
  ``scripts/gen-schema`` wrapper uses this: prod's pgbouncer password
  lives in the database host's ``.pgpass``, so the introspection runs *on* the database host
  via ssh and the rows are piped here.

Freshness (gr676943). The doc is regenerated by hand (it needs prod
ssh), so it lags the migrations between runs. ``scripts/gen-schema``
stamps the newest migration file of the tree it runs in into the Source
line (``snapshot_label``); ``--check`` reads that marker back and counts
the migration files newer than it (``schema_lag``) with no DB and no ssh.
The marker is the tree's newest file, not prod's ledger: run the
regeneration from a tree whose migrations prod has applied. A doc whose
header names no migration is reported as unknown and stale. The check is
advisory, never a ship gate: the lag limit of 10 is a judgment call.

See ``schema-doc-and-manual`` (git-only).
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Iterable
from pathlib import Path

#: ``--check`` exits 1 past this many migrations newer than the marker.
LAG_LIMIT = 10

#: A numbered migration file; the stem (``0324_scope_sha_excludes_logbook``)
#: is what the header marker carries. Four zero-padded digits, so stems
#: order as strings.
_MIGRATION_RE = re.compile(r"^(\d{4}_\w+)\.sql$")

#: The marker ``snapshot_label`` writes into the ``> Source:`` line.
_MARKER_RE = re.compile(r"migrations through (\d{4}_\w+)")

#: One UNION-ALL stream, tab-separated, discriminated by a leading
#: ``col`` / ``fk`` field. Base tables only (``v_*`` views excluded via
#: ``table_type = 'BASE TABLE'``). Column order is restored in the
#: renderer (a UNION can't ``ORDER BY`` the text ordinal numerically).
INTROSPECT_SQL = """
SELECT 'col' AS rec, c.table_name, c.ordinal_position::text, c.column_name,
       c.data_type,
       CASE WHEN pk.column_name IS NOT NULL THEN 'PK' ELSE '' END,
       CASE WHEN fk.column_name IS NOT NULL THEN 'FK' ELSE '' END,
       coalesce(regexp_replace(
                  pg_catalog.col_description(a.attrelid, a.attnum),
                  '\\s+', ' ', 'g'),
                '')
  FROM information_schema.columns c
  JOIN information_schema.tables t
    ON t.table_name = c.table_name AND t.table_schema = c.table_schema
   AND t.table_type = 'BASE TABLE'
  LEFT JOIN pg_catalog.pg_attribute a
    ON a.attrelid = pg_catalog.to_regclass(
         quote_ident(c.table_schema) || '.' || quote_ident(c.table_name))
   AND a.attname = c.column_name AND a.attnum > 0 AND NOT a.attisdropped
  LEFT JOIN (
    SELECT kcu.table_name, kcu.column_name
      FROM information_schema.table_constraints tc
      JOIN information_schema.key_column_usage kcu
        ON kcu.constraint_name = tc.constraint_name
       AND kcu.table_schema = tc.table_schema
     WHERE tc.constraint_type = 'PRIMARY KEY' AND tc.table_schema = 'public'
  ) pk ON pk.table_name = c.table_name AND pk.column_name = c.column_name
  LEFT JOIN (
    SELECT kcu.table_name, kcu.column_name
      FROM information_schema.table_constraints tc
      JOIN information_schema.key_column_usage kcu
        ON kcu.constraint_name = tc.constraint_name
       AND kcu.table_schema = tc.table_schema
     WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = 'public'
  ) fk ON fk.table_name = c.table_name AND fk.column_name = c.column_name
 WHERE c.table_schema = 'public'
UNION ALL
SELECT 'fk', tc.table_name, '0', kcu.column_name, ccu.table_name, ccu.column_name,
       '', ''
  FROM information_schema.table_constraints tc
  JOIN information_schema.key_column_usage kcu
    ON kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema
  JOIN information_schema.constraint_column_usage ccu
    ON ccu.constraint_name = tc.constraint_name AND ccu.table_schema = tc.table_schema
 WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = 'public'
 ORDER BY 1 DESC, 2;
"""


def _safe_type(data_type: str) -> str:
    """Collapse a pg type to a single Mermaid-safe token.

    Mermaid ER attribute types must be one token — ``timestamp with
    time zone`` would break the parse, so non-word characters become
    underscores (``timestamp_with_time_zone``).
    """
    return "".join(ch if ch.isalnum() else "_" for ch in data_type) or "unknown"


def parse_tsv(text: str) -> tuple[list[list[str]], list[list[str]]]:
    """Split the introspection stream into (column rows, fk rows).

    Each line is ``rec\\t...`` — ``col`` rows carry
    ``[rec, table, ord, column, type, pk, fk, comment?]`` (the comment is
    optional so older TSV streams still parse) and ``fk`` rows carry
    ``[rec, from_table, _, from_col, to_table, to_col, _]``. Short or
    blank lines are skipped defensively.
    """
    cols: list[list[str]] = []
    fks: list[list[str]] = []
    for line in text.splitlines():
        if not line.strip():
            continue
        fields = line.split("\t")
        if fields[0] == "col" and len(fields) >= 7:
            cols.append(fields)
        elif fields[0] == "fk" and len(fields) >= 6:
            fks.append(fields)
    return cols, fks


def render_mermaid(
    cols: list[list[str]],
    fks: list[list[str]],
    *,
    snapshot: str | None = None,
) -> str:
    """Render the full ``schema.md`` body from parsed rows.

    Pure: no DB, no I/O. ``snapshot`` is a human label for the source
    (e.g. ``precis_prod @ 2026-06-19``) stamped into the banner.
    """
    # Group columns by table, ordered by ordinal position.
    by_table: dict[str, list[list[str]]] = {}
    for row in cols:
        by_table.setdefault(row[1], []).append(row)
    for rows in by_table.values():
        rows.sort(key=lambda r: int(r[2]))

    tables = sorted(by_table)
    lines: list[str] = []
    lines.append("# Database schema (generated)")
    lines.append("")
    lines.append(
        "> **DO NOT EDIT.** Generated by `precis schema-doc` from the "
        "live database — regenerate with `scripts/gen-schema` rather "
        "than hand-editing, so it can't drift. The hand-drawn "
        "[`schema-v2.puml`](./schema-v2.puml) is the *conceptual* "
        "sketch; this is the *actual*."
    )
    lines.append(">")
    lines.append(
        f"> Source: {snapshot or 'unknown'} · "
        f"{len(tables)} base tables · {len(fks)} foreign keys."
    )
    lines.append(">")
    lines.append(
        "> **No `jobs`/`alerts` tables.** The ops queues are `refs` "
        "rows discriminated by `refs.kind` — jobs are `refs` with "
        "`kind='job'`, alerts with `kind='alert'` — read them through "
        "the `job`/`alert` MCP kinds (`get`/`search`) or "
        "`WHERE kind = 'job'|'alert'`."
    )
    lines.append("")
    lines.append("```mermaid")
    lines.append("erDiagram")
    for table in tables:
        lines.append(f"    {table} {{")
        for row in by_table[table]:
            _, _, _, col, dtype, pk, fk = row[:7]
            key = "PK" if pk == "PK" else ("FK" if fk == "FK" else "")
            attr = f"        {_safe_type(dtype)} {col}"
            if key:
                attr += f" {key}"
            lines.append(attr)
        lines.append("    }")
    # One relationship edge per FK: parent ||--o{ child : "fk_col".
    for fkrow in sorted(fks, key=lambda r: (r[4], r[1], r[3])):
        _, from_table, _, from_col, to_table, to_col = fkrow[:6]
        if from_table == to_table:
            # Self-reference: Mermaid needs a distinct render; keep it
            # simple with a non-identifying edge.
            lines.append(f'    {to_table} ||--o{{ {from_table} : "{from_col} (self)"')
        else:
            lines.append(f'    {to_table} ||--o{{ {from_table} : "{from_col}"')
    lines.append("```")
    lines.append("")
    # Compact listing so the doc is useful even without a Mermaid renderer.
    lines.append("## Tables")
    lines.append("")
    lines.append("| Table | Columns | PK |")
    lines.append("|-------|--------:|----|")
    for table in tables:
        rows = by_table[table]
        pk_cols = ", ".join(r[3] for r in rows if r[5] == "PK") or "—"
        lines.append(f"| `{table}` | {len(rows)} | {pk_cols} |")
    lines.append("")
    # Searchable per-table column list — the greppable form the mermaid
    # block cannot be (gr513884). Comment is the column's COMMENT ON COLUMN
    # text when the schema carries one.
    lines.append("## Columns")
    lines.append("")
    for table in tables:
        lines.append(f"### `{table}`")
        lines.append("")
        lines.append("| Column | Type | Key | Comment |")
        lines.append("|---|---|---|---|")
        for row in by_table[table]:
            _, _, _, col, dtype, pk, fk = row[:7]
            key = "PK" if pk == "PK" else ("FK" if fk == "FK" else "—")
            comment = (row[7] if len(row) > 7 else "").replace("|", "\\|")
            lines.append(f"| `{col}` | {dtype} | {key} | {comment} |")
        lines.append("")
    return "\n".join(lines)


def _migration_stems(names: Iterable[str]) -> list[str]:
    """Stems of the numbered migration files among ``names`` (bare names
    or paths); anything else in the listing is dropped."""
    stems: list[str] = []
    for name in names:
        match = _MIGRATION_RE.match(name.rsplit("/", 1)[-1])
        if match:
            stems.append(match.group(1))
    return stems


def tree_migrations() -> list[str]:
    """Entry names of this tree's built-in migrations directory."""
    migrations_dir = Path(__file__).resolve().parent.parent / "migrations"
    return [entry.name for entry in migrations_dir.iterdir()]


def snapshot_label(db: str, date: str, migrations: Iterable[str] | None = None) -> str:
    """The ``--snapshot`` label ``scripts/gen-schema`` passes:
    ``<db> @ <date> · migrations through <NNNN_name>``, naming the newest
    migration in ``migrations`` (default: this tree's)."""
    stems = _migration_stems(tree_migrations() if migrations is None else migrations)
    label = f"{db} @ {date}"
    return f"{label} · migrations through {max(stems)}" if stems else label


def schema_marker(text: str) -> str | None:
    """The migration the doc's ``> Source:`` line says it reflects, or
    ``None`` when the line names none (docs generated before gr676943).
    Only that line is read: a column comment may use the same words."""
    for line in text.splitlines():
        if line.startswith("> Source:"):
            match = _MARKER_RE.search(line)
            return match.group(1) if match else None
    return None


def schema_lag(header: str, migrations: Iterable[str]) -> int:
    """How many of ``migrations`` are newer than the marker in ``header``
    (the doc text, or its Source line). No marker counts all of them:
    unknown is treated as lagging."""
    stems = _migration_stems(migrations)
    marker = schema_marker(header)
    if marker is None:
        return len(stems)
    return sum(1 for stem in stems if stem > marker)


def check_lag(path: Path) -> int:
    """Print how far the doc at ``path`` lags this tree's migrations.

    Returns the exit code: 1 when the lag is over ``LAG_LIMIT`` or the
    header names no migration, else 0.
    """
    text = path.read_text(encoding="utf-8")
    migrations = tree_migrations()
    marker = schema_marker(text)
    lag = schema_lag(text, migrations)
    if marker is None:
        print(
            f"schema.md lags {lag} migrations (unknown: the header of {path} "
            "names no migration, so all are counted) — regenerate with "
            "scripts/gen-schema"
        )
        return 1
    newest = max(_migration_stems(migrations), default="none")
    stale = lag > LAG_LIMIT
    print(
        f"schema.md lags {lag} migrations (header: through {marker}; "
        f"tree: through {newest})"
        + (" — regenerate with scripts/gen-schema" if stale else "")
    )
    return 1 if stale else 0


def _fetch_via_dsn(dsn: str) -> str:
    """Run the introspection query over psycopg, return the TSV stream.

    Shapes the rows back into the same ``rec\\t...`` lines the
    ``--from-tsv`` path consumes, so both transports hit one parser.
    """
    import psycopg

    out: list[str] = []
    with psycopg.connect(dsn) as conn:
        for row in conn.execute(INTROSPECT_SQL).fetchall():
            out.append("\t".join("" if v is None else str(v) for v in row))
    return "\n".join(out)


def add_parser(sub: argparse._SubParsersAction) -> argparse.ArgumentParser:
    """Register the ``schema-doc`` subparser on ``sub``."""
    parser = sub.add_parser(
        "schema-doc",
        help="Generate a Mermaid ER diagram of the DB schema.",
    )
    parser.add_argument(
        "--database-url",
        default=None,
        help="Override PRECIS_DATABASE_URL (the psycopg source).",
    )
    parser.add_argument(
        "--from-tsv",
        default=None,
        metavar="PATH",
        help="Read pre-fetched introspection rows (tab-separated) "
        "instead of connecting. '-' reads stdin. Used by "
        "scripts/gen-schema (prod auth lives on the database host).",
    )
    parser.add_argument(
        "--snapshot",
        default=None,
        help="Human label for the source, stamped into the banner "
        "(e.g. 'precis_prod @ 2026-06-19 · migrations through "
        "0324_scope_sha_excludes_logbook').",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Generate nothing: print how many migrations the doc at --out "
        "lags this tree, exit 1 past the limit or when its header names "
        "no migration. No database.",
    )
    parser.add_argument(
        "-o",
        "--out",
        default="docs/reference/schema.md",
        help="Output path ('-' for stdout). Default docs/reference/schema.md.",
    )
    return parser


def run(args: argparse.Namespace) -> None:
    """Execute ``precis schema-doc``."""
    if getattr(args, "check", False):
        sys.exit(check_lag(Path(getattr(args, "out", "docs/reference/schema.md"))))

    from_tsv = getattr(args, "from_tsv", None)
    if from_tsv is not None:
        if from_tsv == "-":
            text = sys.stdin.read()
        else:
            text = Path(from_tsv).read_text(encoding="utf-8")
    else:
        from precis.cli._common import resolve_dsn

        dsn = resolve_dsn(getattr(args, "database_url", None))
        text = _fetch_via_dsn(dsn)

    cols, fks = parse_tsv(text)
    if not cols:
        print("schema-doc: no columns found in source", file=sys.stderr)
        sys.exit(1)
    body = render_mermaid(cols, fks, snapshot=getattr(args, "snapshot", None))

    out = getattr(args, "out", "docs/reference/schema.md")
    if out == "-":
        sys.stdout.write(body + "\n")
    else:
        Path(out).write_text(body + "\n", encoding="utf-8")
        n_tables = len({c[1] for c in cols})
        print(f"schema-doc: wrote {out} ({n_tables} tables, {len(fks)} FKs)")


