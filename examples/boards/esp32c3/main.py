"""esp32c3-reference — the batch of ``tests/fixtures/pcb/esp32c3_reference.json`` as a workspace script.

Generated by ``scripts/pcb-batch-to-board``; ``build().to_batch()`` is
byte-equal to that source (``tests/workspaces/test_pcb_board.py``). The
source stays the board's documentation; this file is the construction.
"""

from __future__ import annotations

import precis_geom.pcb as pcb


def build() -> pcb.Board:
    b = pcb.Board("esp32c3-reference")

    # outline and mechanical features
    b.outline({"path": [[0, 0], [300, 0], [300, 300], [0, 300], [0, 0]]})

    # nets
    vbus = b.net("VBUS", current=0.5, voltage=5.0)
    vcc3v3 = b.net("VCC3V3", current=0.5, voltage=3.3)
    gnd = b.net("GND", current=0.5, voltage=0.0)
    sda = b.net("SDA", cls="i2c")
    scl = b.net("SCL", cls="i2c")
    en = b.net("EN")
    boot = b.net("BOOT")
    gpio2 = b.net("GPIO2")
    gpio3 = b.net("GPIO3")
    gpio8 = b.net("GPIO8")
    gpio9 = b.net("GPIO9")
    txd = b.net("TXD")
    rxd = b.net("RXD")
    led_a = b.net("LED_A")
    j1_p5 = b.net("J1_P5")
    j1_p6 = b.net("J1_P6")
    j1_p7 = b.net("J1_P7")
    j1_p8 = b.net("J1_P8")
    en_filt = b.net("EN_FILT")
    pgood_a = b.net("PGOOD_A")

    # parts
    u1 = b.part(
        "U1",
        label="ESP32-C3-MINI-1",
        pins=[
            "3V3",
            "GND1",
            "GND2",
            "GND3",
            "EN",
            "BOOT",
            "SDA",
            "SCL",
            "GPIO2",
            "GPIO3",
            "GPIO8",
            "GPIO9",
            "TXD",
            "RXD",
        ],
    )
    u2 = b.part("U2", label="BME280", pins=["VDD", "GND", "SDA", "SCL"])
    u3 = b.part("U3", label="AMS1117-3.3", pins=["VIN", "GND", "VOUT"])
    d1 = b.part("D1", label="LED-0603", pins=["A", "K"])
    j1 = b.part(
        "J1",
        label="HDR-2.54-1x8",
        pins=["P1", "P2", "P3", "P4", "P5", "P6", "P7", "P8"],
    )
    j2 = b.part("J2", label="HDR-UART-1x4", pins=["VCC", "TXD", "RXD", "GND"])
    r1 = b.part("R1", label="RES-0402", pins=["1", "2"])
    r2 = b.part("R2", label="RES-0402", pins=["1", "2"])
    r3 = b.part("R3", label="RES-0402", pins=["1", "2"])
    r4 = b.part("R4", label="RES-0402", pins=["1", "2"])
    r5 = b.part("R5", label="RES-0402", pins=["1", "2"])
    r6 = b.part("R6", label="RES-0402", pins=["1", "2"])
    d2 = b.part("D2", label="LED-0603-PWR", pins=["A", "K"])
    c1 = b.part("C1", label="CAP-0402-100nF", pins=["1", "2"])
    c2 = b.part("C2", label="CAP-0402-100nF", pins=["1", "2"])
    c3 = b.part("C3", label="CAP-0603-10uF", pins=["1", "2"])
    c4 = b.part("C4", label="CAP-0402-100nF", pins=["1", "2"])
    c5 = b.part("C5", label="CAP-0402-100nF", pins=["1", "2"])
    c6 = b.part("C6", label="CAP-0603-1uF", pins=["1", "2"])
    c7 = b.part("C7", label="CAP-0603-10uF", pins=["1", "2"])
    c8 = b.part("C8", label="CAP-0603-10uF", pins=["1", "2"])
    c9 = b.part("C9", label="CAP-0402-100nF", pins=["1", "2"])
    c10 = b.part("C10", label="CAP-0402-100nF", pins=["1", "2"])
    c11 = b.part("C11", label="CAP-0603-1uF", pins=["1", "2"])
    c12 = b.part("C12", label="CAP-0402-100nF", pins=["1", "2"])
    c13 = b.part("C13", label="CAP-0402-100nF", pins=["1", "2"])
    c14 = b.part("C14", label="CAP-0402-100nF", pins=["1", "2"])
    c15 = b.part("C15", label="CAP-0603-1uF", pins=["1", "2"])
    c16 = b.part("C16", label="CAP-0402-100nF", pins=["1", "2"])

    # pin classes (gr520810 — every tied pin is classified; no datasheets,
    # so each class carries an explicit assume note)
    u1["3V3"].etype(
        "power_in", max_current_a=0.5, max_voltage_v=3.3, assume="esp32 vdd"
    )
    for p in u1.pins("GND1", "GND2", "GND3"):
        p.etype("power_in", max_current_a=0.5, max_voltage_v=3.3, assume="esp32 gnd")
    u1["EN"].etype("input", fmax_hz=0.0, assume="chip enable")
    u1["BOOT"].etype("input", fmax_hz=0.0, assume="boot strap")
    u1["SDA"].etype("bidi", fmax_hz=400e3, assume="i2c sda")
    u1["SCL"].etype("output", fmax_hz=400e3, assume="i2c scl")
    for p in u1.pins("GPIO2", "GPIO3", "GPIO8", "GPIO9"):
        p.etype("bidi", fmax_hz=1e6, assume="gpio")
    u1["TXD"].etype("output", fmax_hz=1e6, assume="uart tx")
    u1["RXD"].etype("input", fmax_hz=1e6, assume="uart rx")
    u2["VDD"].etype(
        "power_in", max_current_a=0.5, max_voltage_v=3.3, assume="bme280 vdd"
    )
    u2["GND"].etype(
        "power_in", max_current_a=0.5, max_voltage_v=3.3, assume="bme280 gnd"
    )
    u2["SDA"].etype("bidi", fmax_hz=400e3, assume="i2c sda")
    u2["SCL"].etype("input", fmax_hz=400e3, assume="i2c scl")
    u3["VIN"].etype(
        "power_in", max_current_a=0.5, max_voltage_v=5.0, assume="ldo vin (usb 5v)"
    )
    u3["GND"].etype("power_in", max_current_a=0.5, max_voltage_v=5.0, assume="ldo gnd")
    u3["VOUT"].etype(
        "power_out", max_current_a=0.5, max_voltage_v=3.3, assume="ldo 3v3"
    )
    for led in (d1, d2):
        led["A"].etype("input", fmax_hz=0.0, assume="led anode")
        led["K"].etype("input", fmax_hz=0.0, assume="led cathode")
    j1["P1"].etype("power_out", max_current_a=0.5, max_voltage_v=3.3, assume="hdr 3v3")
    j1["P2"].etype("power_in", max_current_a=0.5, max_voltage_v=3.3, assume="hdr gnd")
    j1["P3"].etype("bidi", fmax_hz=400e3, assume="i2c sda")
    j1["P4"].etype("output", fmax_hz=400e3, assume="i2c scl")
    for p in j1.pins("P5", "P6", "P7", "P8"):
        p.etype("bidi", fmax_hz=1e6, assume="hdr gpio")
    j2["VCC"].etype("power_out", max_current_a=0.5, max_voltage_v=3.3, assume="hdr 3v3")
    j2["TXD"].etype("output", fmax_hz=1e6, assume="uart tx")
    j2["RXD"].etype("input", fmax_hz=1e6, assume="uart rx")
    j2["GND"].etype("power_in", max_current_a=0.5, max_voltage_v=3.3, assume="hdr gnd")
    for r, note in (
        (r1, "i2c pullup"),
        (r2, "i2c pullup"),
        (r3, "en pullup"),
        (r4, "led series"),
        (r5, "power led series"),
        (r6, "boot pulldown"),
    ):
        for p in r.pins("1", "2"):
            p.etype("passive", fmax_hz=0.0, assume=note)
    for cap in (c1, c2, c4, c5, c9, c10, c12, c13, c14):
        for p in cap.pins("1", "2"):
            p.etype("passive", fmax_hz=0.0, assume="100nf cap")
    for cap in (c3, c7, c8):
        for p in cap.pins("1", "2"):
            p.etype("passive", fmax_hz=0.0, assume="10uf bulk")
    for cap in (c6, c11, c15, c16):
        for p in cap.pins("1", "2"):
            p.etype("passive", fmax_hz=0.0, assume="1uf cap")

    # connections (authored order)
    vcc3v3.tie(u1["3V3"])
    gnd.tie(u1["GND1"], u1["GND2"], u1["GND3"])
    en.tie(u1["EN"])
    boot.tie(u1["BOOT"])
    sda.tie(u1["SDA"])
    scl.tie(u1["SCL"])
    gpio2.tie(u1["GPIO2"])
    gpio3.tie(u1["GPIO3"])
    gpio8.tie(u1["GPIO8"])
    gpio9.tie(u1["GPIO9"])
    txd.tie(u1["TXD"])
    rxd.tie(u1["RXD"])
    vcc3v3.tie(u2["VDD"])
    gnd.tie(u2["GND"])
    sda.tie(u2["SDA"])
    scl.tie(u2["SCL"])
    vbus.tie(u3["VIN"])
    gnd.tie(u3["GND"])
    vcc3v3.tie(u3["VOUT"])
    led_a.tie(d1["A"])
    gnd.tie(d1["K"])
    led_a.tie(r4["1"])
    vcc3v3.tie(r4["2"])
    sda.tie(r1["1"])
    vcc3v3.tie(r1["2"])
    scl.tie(r2["1"])
    vcc3v3.tie(r2["2"])
    en.tie(r3["1"])
    vcc3v3.tie(r3["2"])
    en_filt.tie(c12["1"])
    gnd.tie(c12["2"])
    boot.tie(r6["1"])
    gnd.tie(r6["2"])
    boot.tie(c16["1"])
    gnd.tie(c16["2"])
    vcc3v3.tie(r5["1"])
    pgood_a.tie(r5["2"], d2["A"])
    gnd.tie(d2["K"])
    vcc3v3.tie(j1["P1"])
    gnd.tie(j1["P2"])
    sda.tie(j1["P3"])
    scl.tie(j1["P4"])
    j1_p5.tie(j1["P5"])
    j1_p6.tie(j1["P6"])
    j1_p7.tie(j1["P7"])
    j1_p8.tie(j1["P8"])
    vcc3v3.tie(j2["VCC"])
    txd.tie(j2["TXD"])
    rxd.tie(j2["RXD"])
    gnd.tie(j2["GND"])
    vcc3v3.tie(c1["1"])
    gnd.tie(c1["2"])
    vcc3v3.tie(c2["1"])
    gnd.tie(c2["2"])
    vcc3v3.tie(c3["1"])
    gnd.tie(c3["2"])
    vcc3v3.tie(c4["1"])
    gnd.tie(c4["2"])
    vcc3v3.tie(c5["1"])
    gnd.tie(c5["2"])
    vcc3v3.tie(c6["1"])
    gnd.tie(c6["2"])
    vbus.tie(c7["1"])
    gnd.tie(c7["2"])
    vcc3v3.tie(c8["1"])
    gnd.tie(c8["2"])
    vcc3v3.tie(c9["1"])
    gnd.tie(c9["2"])
    vcc3v3.tie(c10["1"])
    gnd.tie(c10["2"])
    vcc3v3.tie(c11["1"])
    gnd.tie(c11["2"])
    vcc3v3.tie(c13["1"])
    gnd.tie(c13["2"])
    vcc3v3.tie(c14["1"])
    gnd.tie(c14["2"])
    vcc3v3.tie(c15["1"])
    gnd.tie(c15["2"])
    return b


if __name__ == "__main__":
    pcb.run(build(), "out")
