"""Gate-fast selection (me580555): the blocking ~5-minute leg of check.yml.

The selection is the union of four tiers, minus files whose every test is
``nightly``-marked (``-m "not nightly"`` collects nothing from them) and
files no longer on disk (history outlives a renamed or deleted test):

  floor      every measured test file with ``seconds <= floor_seconds``
             (tests/shard_weights.json, LPT-packed per-file totals)
  history    files that held a failing id in a red ``ci/**`` / ``release/**``
             check.yml run since 2026-10-01 (tests/gate_fast.json,
             regenerated by scripts/gate-fast-refit)
  contract   scripts/impacted-tests' always-on/contract tier — read live
             from that script, never duplicated here
  impacted   the files ``scripts/impacted-tests BASE HEAD --json`` names;
             FULL means the whole suite minus nightly files (a harness
             diff is not honestly selectable, so gate-fast IS the gate
             and check.yml skips the soak)

Bounds: the partition is by FILE, so one fat file sets the floor of the
slowest shard — a file whose non-nightly seconds exceed
``fast_shard_cap_seconds`` is selectable only by ``impacted`` (with a
stderr note; the soak covers it otherwise). The total predicted
non-nightly seconds stay under ``fast_budget_seconds``; over budget the
history files with the lowest red-incident hit count are dropped first —
floor and contract files are never dropped.

tests/gate_fast.json is committed and looks like::

    {"generated_at": "<UTC Z>", "source_run": 42354225792,
     "floor_seconds": 2.0, "history_files": ["tests/...", ...],
     "history_hits": {"tests/...": 3}, "contract_files": ["tests/...", ...],
     "nightly_tests": {"tests/f.py": {"test_x": 42.0}},
     "nightly_seconds": {"tests/f.py": 60.0}}

``nightly_tests`` records the marked functions with their measured seconds
(the marker test in tests/test_gate_fast.py reads it); ``nightly_seconds``
is the file's total junit seconds of those marked functions — including
params under 30 s, which a function-level mark removes too — so a file's
non-nightly cost is ``seconds[f] - nightly_seconds[f]``.

The outer planner is stdlib-only; impacted Python analysis needs project
dependencies, so its subprocess uses the frozen project runtime rather than
inheriting the planner's project-free interpreter.
"""

from __future__ import annotations

import ast
import json
import runpy
import subprocess
from pathlib import Path
from typing import Any

FLOOR_SECONDS = 2.0
#: 20 xdist workers across the 10 gate-fast shards x a 210 s test budget.
FAST_BUDGET_SECONDS = 4200.0
#: One file is the partition's atom: bigger than this and a shard can
#: never finish inside ~5 min of tests, so only `impacted` may pull it in.
FAST_SHARD_CAP_SECONDS = 300.0
#: A test function measured over this on the FULL run carries the
#: ``nightly`` mark: the gate's ``-m "not nightly"`` deselect drops it,
#: and the file's gate cost falls to ``seconds - nightly_seconds``.
NIGHTLY_CAP_SECONDS = 30.0
SHARDS = 10

WEIGHTS_JSON = "tests/shard_weights.json"
GATE_FAST_JSON = "tests/gate_fast.json"
IMPACTED = "scripts/impacted-tests"

ImpactedRunner = Any  # Callable[[list[str]], subprocess.CompletedProcess[str]]


def load_seconds(root: Path, path: Path | None = None) -> dict[str, float] | None:
    """The ``seconds`` table, or ``None`` when the file is unreadable —
    a corrupt weights table must fail loudly, never silently offer no
    files (an empty valid table is still ``{}`` and equally unusable —
    ``select`` refuses both)."""
    p = path or root / WEIGHTS_JSON
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if not isinstance(data, dict):
        return None
    return {str(k): float(v) for k, v in (data.get("seconds") or {}).items()}


def load_gate_file(root: Path, path: Path | None = None) -> dict[str, Any] | None:
    """tests/gate_fast.json, or ``None`` when unreadable (see above)."""
    p = path or root / GATE_FAST_JSON
    try:
        data = json.loads(p.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return data if isinstance(data, dict) else None


def contract_files(root: Path) -> set[str]:
    """impacted-tests' always-on/contract tier as FILE paths.

    CONTRACT + the static always-on floors (smoke, docs-hygiene, the
    migration/schema set) — the targets every diff pays regardless of
    evidence. Read live from the script (runpy): the selector is the one
    place a coupling may live, and this must not become a second copy.
    """
    mod = runpy.run_path(str(root / IMPACTED))
    out: set[str] = set()
    for t in (
        list(mod.get("CONTRACT") or [])
        + list(mod.get("SMOKE_TESTS") or [])
        + list(mod.get("_DOCS_HYGIENE") or [])
        + list(mod["migration_set"](root))
    ):
        out.add(str(t).split("::", 1)[0])
    return out


# ── nightly marks (AST, no collection) ─────────────────────────────────


def _deco_names(deco: ast.expr) -> str:
    """The decorator's trailing name: ``pytest.mark.nightly(...)`` →
    ``"nightly"``, a bare ``@nightly`` → ``"nightly"``."""
    node = deco.func if isinstance(deco, ast.Call) else deco
    if isinstance(node, ast.Attribute):
        return node.attr
    if isinstance(node, ast.Name):
        return node.id
    return ""


def _module_pytestmark_nightly(tree: ast.Module) -> bool:
    for stmt in tree.body:
        if isinstance(stmt, ast.Assign):
            names = [t.id for t in stmt.targets if isinstance(t, ast.Name)]
            if "pytestmark" in names and "nightly" in ast.dump(stmt.value):
                return True
    return False


def _fn_nightly(fn: ast.FunctionDef | ast.AsyncFunctionDef) -> bool:
    return any(_deco_names(d) == "nightly" for d in fn.decorator_list)


def file_is_all_nightly(path: Path) -> bool:
    """Every ``test_*`` function in the file carries the nightly mark —
    directly, or via an enclosing class, or via module ``pytestmark``.
    A file with no test functions is not "all nightly"."""
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (OSError, SyntaxError):
        return False
    module_mark = _module_pytestmark_nightly(tree)

    def visit(node: ast.AST, inherited: bool) -> tuple[int, int]:
        """(test fns, nightly fns) under node."""
        total = marked = 0
        for child in ast.iter_child_nodes(node):
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if child.name.startswith("test_"):
                    total += 1
                    if inherited or _fn_nightly(child):
                        marked += 1
            elif isinstance(child, ast.ClassDef):
                cls_mark = inherited or _fn_nightly(child)  # decorators share the check
                t, m = visit(child, cls_mark)
                total += t
                marked += m
        return total, marked

    total, marked = visit(tree, module_mark)
    return total > 0 and total == marked


def nightly_seconds(gate: dict[str, Any]) -> dict[str, float]:
    return {str(k): float(v) for k, v in (gate.get("nightly_seconds") or {}).items()}


def non_nightly_seconds(
    file: str,
    seconds: dict[str, float],
    nightly_s: dict[str, float],
) -> float:
    return max(0.0, seconds.get(file, 0.0) - nightly_s.get(file, 0.0))


# ── impacted tier ──────────────────────────────────────────────────────


def impacted(
    root: Path,
    base: str,
    head: str,
    *,
    runner: Any = None,
) -> dict[str, Any]:
    """``scripts/impacted-tests BASE HEAD --json`` — the ONE diff->tests
    selector, under the frozen project runtime: Python analysis imports
    project dependencies unavailable to the stdlib-only outer planner.
    A fetch/parse failure returns ``error``, which ``select`` widens to
    FULL — never narrows. Diagnostics retain the bounded exception tail."""
    run = runner or (
        lambda argv: subprocess.run(
            argv,
            cwd=root,
            capture_output=True,
            text=True,
            encoding="utf-8",
            timeout=300,
            check=False,
        )
    )
    try:
        cp = run(
            [
                "uv",
                "run",
                "--frozen",
                "--project",
                str(root),
                "python",
                IMPACTED,
                base,
                head,
                "--json",
            ]
        )
    except (OSError, subprocess.SubprocessError) as exc:
        return {
            "mode": "error",
            "files": {},
            "full_because": [],
            "notes": [str(exc)[-1000:]],
        }
    if cp.returncode != 0:
        return {
            "mode": "error",
            "files": {},
            "full_because": [],
            "notes": [
                f"impacted-tests exit {cp.returncode}: {cp.stderr.strip()[-1000:]}"
            ],
        }
    try:
        out = json.loads(cp.stdout)
    except ValueError:
        return {
            "mode": "error",
            "files": {},
            "full_because": [],
            "notes": [f"impacted-tests: unparseable JSON ({cp.stdout[:120]!r})"],
        }
    return out if isinstance(out, dict) else {"mode": "error", "files": {}}


# ── selection ──────────────────────────────────────────────────────────


def select(
    root: Path,
    base: str,
    head: str,
    *,
    floor: float = FLOOR_SECONDS,
    budget: float = FAST_BUDGET_SECONDS,
    cap: float = FAST_SHARD_CAP_SECONDS,
    seconds: dict[str, float] | None = None,
    gate: dict[str, Any] | None = None,
    contract: set[str] | None = None,
    impacted_result: dict[str, Any] | None = None,
    exists: Any = None,
    all_nightly: Any = None,
    disk_files: list[str] | None = None,
) -> dict[str, Any]:
    """The gate-fast file list. Returns ``{files, full, why, dropped,
    over_cap_impacted, explain, seconds_pred, seconds}`` — ``files``
    sorted, ``explain`` maps file -> tier names, ``seconds`` is the cost
    table actually used (disk files missing from shard_weights.json get
    the median measured weight so packing and floor/cap accounting still
    work). ``{error: ...}`` instead when a committed input is unreadable
    or empty — a corrupt table must fail loudly, never silently offer no
    files. A file not on disk is dropped before any accounting: history
    outlives the tree, and a stale record reaching pytest reds every
    shard as "file not found"."""
    if seconds is None:
        seconds = load_seconds(root)
        if not seconds:
            return {"error": f"{WEIGHTS_JSON} unreadable or empty — refusing to select"}
    if gate is None:
        gate = load_gate_file(root)
        if not gate:
            return {
                "error": f"{GATE_FAST_JSON} unreadable or empty — refusing to select"
            }
    contract = contract_files(root) if contract is None else contract
    nightly_s = nightly_seconds(gate)
    is_gone = (
        (lambda f: not exists(f)) if exists else (lambda f: not (root / f).is_file())
    )
    is_all_nightly = all_nightly or (lambda f: file_is_all_nightly(root / f))
    if disk_files is None:
        # Plain filesystem walk — git ls-files fails inside the ship
        # container for worktrees. Same filter as ci-shard-plan's
        # test_files: tests/**/test_*.py.
        disk_files = sorted(
            p.relative_to(root).as_posix()
            for p in (root / "tests").rglob("test_*.py")
            if p.is_file()
        )
    # A test file on disk missing from the seconds table still needs a
    # weight for floor/cap/budget accounting: the median measured file is
    # the conservative default (and lands under the floor anyway when the
    # table's typical file is fast).
    median = sorted(seconds.values())[len(seconds) // 2] if seconds else 0.0
    sec = {f: median for f in disk_files}
    sec.update(seconds)

    history = [str(f) for f in (gate.get("history_files") or [])]
    hits = {str(k): int(v) for k, v in (gate.get("history_hits") or {}).items()}

    tiers: dict[str, set[str]] = {}

    def offer(f: str, tier: str) -> None:
        tiers.setdefault(f, set()).add(tier)

    for f, s in sec.items():
        if s <= floor:
            offer(f, "floor")
    for f in history:
        offer(f, "history")
    for f in contract:
        offer(f, "contract")

    imp = impacted_result
    if imp is None:
        imp = impacted(root, base, head)
    # Anything but a clean `selected` widens to the whole suite: a harness
    # diff can't be honestly subset, and an impacted-tests failure is the
    # same "we cannot select" — under-gating is the wrong failure. FULL is
    # the disk, not the seconds table: a file nobody measured yet would
    # otherwise never run on a harness release.
    full = imp.get("mode") != "selected"
    why = "; ".join(str(w) for w in imp.get("full_because") or [])
    over_cap_impacted: list[str] = []
    if full:
        for f in disk_files:
            offer(f, "impacted")
    else:
        for t in imp.get("files") or {}:
            offer(str(t).split("::", 1)[0], "impacted")

    # Gone files first — a stale history record is not an offer, and its
    # stale seconds must not consume budget a live file could use. Then
    # the shard cap: a file fatter than 300 s of non-nightly time can
    # never shard under ~5 min — only `impacted` may still pull it in.
    for f in list(tiers):
        if is_gone(f):
            del tiers[f]
            continue
        cost = non_nightly_seconds(f, sec, nightly_s)
        if cost <= cap:
            continue
        if "impacted" in tiers[f]:
            over_cap_impacted.append(f)
        else:
            del tiers[f]

    # Budget: drop the lowest-hit history files until it fits — but never
    # a file some other tier also claims (contract/floor/impacted stand).
    dropped: list[str] = []
    total = sum(non_nightly_seconds(f, sec, nightly_s) for f in tiers)
    if total > budget:
        hist_only = [f for f in tiers if tiers[f] == {"history"}]
        for f in sorted(hist_only, key=lambda x: (hits.get(x, 0), x)):
            if total <= budget:
                break
            total -= non_nightly_seconds(f, sec, nightly_s)
            del tiers[f]
            dropped.append(f)

    files = sorted(f for f in tiers if not is_all_nightly(f))
    return {
        "files": files,
        "full": full,
        "why": why,
        "dropped": dropped,
        "over_cap_impacted": sorted(over_cap_impacted),
        "explain": {f: sorted(t) for f, t in sorted(tiers.items())},
        "seconds_pred": round(
            sum(non_nightly_seconds(f, sec, nightly_s) for f in files), 1
        ),
        "seconds": sec,
        "nightly_seconds": nightly_s,
        "notes": list(imp.get("notes") or []),
    }


def pack(
    files: list[str],
    seconds: dict[str, float],
    nightly_s: dict[str, float],
    n: int = SHARDS,
) -> tuple[dict[str, list[str]], list[float]]:
    """LPT-pack positive costs, then spread zero-cost files by file count.

    Zero-cost files still incur collection/setup; measured-load ordering
    would pile them onto one shard when its initial load is lowest.
    Preserve measured loads, using load/index only to break count ties.
    Positive-cost packing follows ci-shard-plan's shard_files, including
    path-sorted buckets. The sort is not cosmetic: check.yml hands each
    bucket to pytest as bare file args, and pytest 9.1's deferred conftest
    binding attaches a directory's conftest fixtures to the first Directory
    node collected for it — while every bare file arg under a package dir
    re-collects that dir with fresh child nodes. A ``tests/test_*.py``
    argv entry between two ``tests/<pkg>/*.py`` entries therefore unbinds
    the pkg conftest for the second ("fixture 'x' not found" — the CI
    leg-5/leg-7 failure). Sorted argv keeps every subtree's files
    contiguous, so no parent-dir file arg ever lands inside one."""
    load = [0.0] * n
    out: dict[str, list[str]] = {str(k): [] for k in range(1, n + 1)}
    order = sorted(
        files,
        key=lambda f: (-non_nightly_seconds(f, seconds, nightly_s), f),
    )
    zero_cost: list[str] = []
    for f in order:
        cost = non_nightly_seconds(f, seconds, nightly_s)
        if cost == 0:
            zero_cost.append(f)
            continue
        k = min(range(n), key=lambda i: (load[i], i))
        load[k] += cost
        out[str(k + 1)].append(f)
    for f in zero_cost:
        k = min(range(n), key=lambda i: (len(out[str(i + 1)]), load[i], i))
        out[str(k + 1)].append(f)
    for bucket in out.values():
        bucket.sort()
    return out, load
